<?php

declare(strict_types=1);

namespace Nowo\ManualKitBundle\DependencyInjection;

use InvalidArgumentException;
use Nowo\ManualKitBundle\Render\DeviceViews;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

use function array_column;
use function array_unique;
use function count;
use function is_string;
use function sprintf;
use function trim;

/**
 * `nowo_manual_kit` configuration; see docs/CONFIGURATION.md.
 *
 * @author Héctor Franco Aceituno <hectorfranco@nowo.tech>
 * @copyright 2026 Nowo.tech
 */
final class Configuration implements ConfigurationInterface
{
    public const string ALIAS = 'nowo_manual_kit';

    /**
     * {@inheritDoc}
     */
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $tree = new TreeBuilder(self::ALIAS);
        $tree->getRootNode()
            ->children()
                ->scalarNode('directory')
                    ->info('The manual: manifest.yaml, the source-language chapters, images/ and one folder per translation locale.')
                    ->defaultValue('%kernel.project_dir%/docs/manual')
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('source_locale')
                    ->info('Language of the root files.')
                    ->defaultValue('en')
                    ->cannotBeEmpty()
                    ->validate()
                        ->ifTrue(static fn (mixed $locale): bool => !self::isLocale($locale))
                        ->then(static fn (mixed $locale): never => throw new InvalidArgumentException(sprintf('Invalid "nowo_manual_kit.source_locale" %s: expected a locale such as "en" or "pt_BR".', json_encode($locale))))
                    ->end()
                ->end()
                ->arrayNode('locales')
                    ->info('Locales that may have a translation folder (default: kernel.enabled_locales).')
                    ->scalarPrototype()
                        ->validate()
                            ->ifTrue(static fn (mixed $locale): bool => !self::isLocale($locale))
                            ->then(static fn (mixed $locale): never => throw new InvalidArgumentException(sprintf('Invalid entry %s in "nowo_manual_kit.locales": expected locales such as "es" or "pt_BR".', json_encode($locale))))
                        ->end()
                    ->end()
                    ->defaultValue([])
                ->end()
                ->scalarNode('role')
                    ->info('Role (or attribute) needed to read the manual; empty = public.')
                    ->defaultValue('ROLE_USER')
                    ->validate()
                        ->ifTrue(static fn (mixed $role): bool => !is_string($role))
                        ->thenInvalid('"nowo_manual_kit.role" must be a role / security attribute string ("" makes the manual public), got %s.')
                    ->end()
                ->end()
                ->scalarNode('admin_role')
                    ->info('Readers of `audience: admin` chapters and `<!-- audience: admin -->` blocks (default ROLE_ADMIN). 1.13: an alias of audiences.admin; setting both to different values fails the build.')
                    ->defaultNull()
                    // '' would mean "everyone" for admin content: never allowed.
                    ->validate()
                        ->ifTrue(static fn (mixed $role): bool => !is_string($role) || trim($role) === '')
                        ->thenInvalid('"nowo_manual_kit.admin_role" must be a non-empty role / security attribute, got %s.')
                    ->end()
                ->end()
                ->arrayNode('audiences')
                    ->info('1.13: named audiences, name => role or security attribute (checked with isGranted(), so voters and the role hierarchy apply), e.g. {developer: ROLE_DEVELOPER}. "member" (every reader) is built in; "admin" defaults to admin_role.')
                    ->useAttributeAsKey('name')
                    ->normalizeKeys(false)
                    ->scalarPrototype()
                        ->validate()
                            ->ifTrue(static fn (mixed $role): bool => !is_string($role) || trim($role) === '')
                            ->thenInvalid('Every audience of "nowo_manual_kit.audiences" needs a non-empty role / security attribute, got %s.')
                        ->end()
                    ->end()
                    ->defaultValue([])
                ->end()
                ->scalarNode('default_audience')
                    ->info('1.13: the audience of a chapter whose manifest row names none: "member" (default, every reader) or an audience of the default root.')
                    ->defaultValue('member')
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('default_firewalls')
                    ->info('1.13: firewalls the default root (role, routes.php) is served in; [] (default) = any firewall no root of "roots" lists.')
                    ->scalarPrototype()->cannotBeEmpty()->end()
                    ->defaultValue([])
                ->end()
                ->arrayNode('roots')
                    ->info('1.13: other manual roots served from the same manifest, each under its own route import (type: nowo_manual, resource: <root>) and firewall, with only the chapters of its audiences. The default root keeps "member" and every audience no root lists.')
                    ->useAttributeAsKey('name')
                    ->normalizeKeys(false)
                    ->arrayPrototype()
                        ->children()
                            ->arrayNode('audiences')
                                ->info('The audiences this root serves (taken out of the default root).')
                                ->isRequired()
                                ->requiresAtLeastOneElement()
                                ->scalarPrototype()->end()
                            ->end()
                            ->scalarNode('role')
                                ->info('Role or security attribute needed to open this root ("" = every visitor of its firewall).')
                                ->isRequired()
                                ->validate()
                                    ->ifTrue(static fn (mixed $role): bool => !is_string($role))
                                    ->thenInvalid('The "role" of a manual root must be a role / security attribute string, got %s.')
                                ->end()
                            ->end()
                            ->scalarNode('home')
                                ->info('Slug of the chapter the root index serves.')
                                ->defaultValue('README')
                                ->validate()
                                    ->ifTrue(static fn (mixed $slug): bool => !is_string($slug) || preg_match('/^[A-Za-z0-9-]+\z/', $slug) !== 1)
                                    ->thenInvalid('The "home" of a manual root must be a chapter slug, got %s.')
                                ->end()
                            ->end()
                            ->arrayNode('firewalls')
                                ->info('Firewalls this root is served in (required, at least one); it is a 404 anywhere else, and the SearchKit group and manual_href() of these firewalls use it.')
                                ->isRequired()
                                ->requiresAtLeastOneElement()
                                ->scalarPrototype()->cannotBeEmpty()->end()
                            ->end()
                        ->end()
                    ->end()
                    ->defaultValue([])
                ->end()
                ->scalarNode('docs_url')
                    ->info('Base URL of the published docs (e.g. https://github.com/acme/app/blob/main/docs/) for links outside the manual.')
                    ->defaultValue('')
                    ->validate()
                        ->ifTrue(static fn (mixed $url): bool => $url !== '' && !self::isHttpUrl($url))
                        ->thenInvalid('"nowo_manual_kit.docs_url" must be "" or an absolute http(s) URL, got %s.')
                    ->end()
                ->end()
                ->booleanNode('in_app')
                    ->info('manual_href() opens the in-app chapter (true) or always the published copy (false).')
                    ->defaultTrue()
                ->end()
                ->scalarNode('template')
                    ->info('Twig template of a chapter page (variables: rendered, chapters, previous, next).')
                    ->defaultValue('@NowoManualKitBundle/chapter.html.twig')
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('layout')
                    ->info('Layout the default chapter template extends (blocks: title, stylesheets, body).')
                    ->defaultValue('@NowoManualKitBundle/layout.html.twig')
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('groups')
                    ->info('1.8: order and labels of the chapter groups in the navigation. Listed groups come first, in this order; groups of the manifest not listed follow in manifest order. A null label uses group.<key> of the NowoManualKitBundle domain. Empty (default): manifest order, bundle labels.')
                    ->arrayPrototype()
                        ->beforeNormalization()
                            ->ifString()
                            ->then(static fn (string $key): array => ['key' => $key])
                        ->end()
                        ->children()
                            ->scalarNode('key')
                                ->info('The manifest `group` value.')
                                ->isRequired()
                                ->cannotBeEmpty()
                            ->end()
                            ->scalarNode('label')
                                ->info('Translation key of the heading (null: group.<key> in NowoManualKitBundle).')
                                ->defaultNull()
                            ->end()
                            ->scalarNode('translation_domain')
                                ->info('Domain of `label`.')
                                ->defaultValue('messages')
                                ->cannotBeEmpty()
                            ->end()
                        ->end()
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $groups): bool => count(array_unique(array_column($groups, 'key'))) !== count($groups))
                        ->thenInvalid('nowo_manual_kit.groups lists a group key twice.')
                    ->end()
                ->end()
                ->arrayNode('redirects')
                    ->info('1.11: chapters and anchors that moved, old → new: "old-slug: new-slug" and "\'old-slug#anchor\': \'new-slug#anchor\'". Internal slugs only (never a URL). Merged with the `redirects:` file the manifest names; validated when the container is built (no cycle, chains collapsed to one hop). GET /manual/<old-slug> answers 301 to the new chapter; a small script moves the reader to the mapped anchor.')
                    ->useAttributeAsKey('from')
                    ->normalizeKeys(false)
                    ->scalarPrototype()->end()
                    ->defaultValue([])
                ->end()
                ->arrayNode('device_views')
                    ->info('1.12: desktop / phone views of a chapter: <!-- device: phone|desktop --> blocks, the Desktop / Phone switch and phone companion images. Off (default): the 1.11 rendering, byte for byte.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->info('Turn the device blocks, the switch and the phone companions on.')
                            ->defaultFalse()
                        ->end()
                        ->integerNode('breakpoint')
                            ->info('Viewport width in CSS px below which the phone view is the default (until the reader chooses).')
                            ->defaultValue(DeviceViews::DEFAULT_BREAKPOINT)
                            ->min(240)
                            ->max(4096)
                        ->end()
                        ->scalarNode('image_suffix')
                            ->info('Inserted before the extension to find the phone companion of an image: images/x.webp → images/x.phone.webp.')
                            ->defaultValue(DeviceViews::DEFAULT_IMAGE_SUFFIX)
                            ->validate()
                                ->ifTrue(static fn (mixed $suffix): bool => !is_string($suffix) || preg_match(DeviceViews::IMAGE_SUFFIX_PATTERN, $suffix) !== 1)
                                ->thenInvalid('"nowo_manual_kit.device_views.image_suffix" must be one of "." "_" "-" followed by 1 to 32 letters, digits, "_" or "-" (e.g. ".phone"), got %s.')
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->booleanNode('standalone_lightbox')
                    ->info('The default chapter template loads the self-contained lightbox script (js/manual-lightbox.js) — for applications that do not register the Stimulus peer in their own build.')
                    ->defaultFalse()
                ->end()
                ->scalarNode('cache')
                    ->info('Cache pool for rendered chapters.')
                    ->defaultValue('cache.app')
                    ->cannotBeEmpty()
                ->end()
                ->arrayNode('machine_translation')
                    ->info('nowo:manual:translate — machine translation of missing / outdated chapters.')
                    ->addDefaultsIfNotSet()
                    ->validate()
                        ->ifTrue(static fn (array $machine): bool => $machine['provider'] === 'libretranslate' && $machine['url'] === '')
                        ->thenInvalid('"nowo_manual_kit.machine_translation.url" is required when "provider" is "libretranslate" (e.g. http://libretranslate:5000).')
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $machine): bool => $machine['provider'] === 'deepl' && $machine['api_key'] === '')
                        ->thenInvalid('"nowo_manual_kit.machine_translation.api_key" is required when "provider" is "deepl" (e.g. %%env(DEEPL_API_KEY)%%).')
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $machine): bool => $machine['provider'] === 'service' && $machine['service'] === '')
                        ->thenInvalid('"nowo_manual_kit.machine_translation.service" is required when "provider" is "service" (the id of your MachineTranslatorInterface service).')
                    ->end()
                    ->validate()
                        ->ifTrue(static fn (array $machine): bool => $machine['max_duration'] < $machine['timeout'])
                        ->thenInvalid('"nowo_manual_kit.machine_translation.max_duration" must be greater than or equal to "timeout".')
                    ->end()
                    ->children()
                        ->enumNode('provider')
                            ->info('none (the command is off), deepl (DeepL API; a key ending in :fx is DeepL API Free), libretranslate, or service (your own MachineTranslatorInterface, see "service").')
                            ->values(['none', 'deepl', 'libretranslate', 'service'])
                            ->defaultValue('none')
                        ->end()
                        ->scalarNode('service')
                            ->info('1.9: with provider "service", the id of a service implementing Nowo\\ManualKitBundle\\Translation\\MachineTranslatorInterface (e.g. an adapter to your translation gateway).')
                            ->defaultValue('')
                        ->end()
                        ->scalarNode('api_key')
                            ->info('Provider key, e.g. %env(DEEPL_API_KEY)% (optional for a self-hosted LibreTranslate).')
                            ->defaultValue('')
                        ->end()
                        ->scalarNode('url')
                            ->info('LibreTranslate base URL (required for it), or a DeepL endpoint override.')
                            ->defaultValue('')
                            ->validate()
                                ->ifTrue(static fn (mixed $url): bool => $url !== '' && !self::isHttpUrl($url))
                                ->thenInvalid('"nowo_manual_kit.machine_translation.url" must be "" or an absolute http(s) URL, got %s.')
                            ->end()
                        ->end()
                        ->floatNode('timeout')
                            ->info('Idle timeout in seconds of each provider request (Symfony HttpClient "timeout").')
                            ->defaultValue(30.0)
                            ->min(1.0)
                        ->end()
                        ->floatNode('max_duration')
                            ->info('Hard deadline in seconds of each provider request, connection included (HttpClient "max_duration").')
                            ->defaultValue(120.0)
                            ->min(1.0)
                        ->end()
                        ->enumNode('formality')
                            ->info('DeepL register: default, less (informal "tú / du") or more.')
                            ->values(['default', 'less', 'more'])
                            ->defaultValue('default')
                        ->end()
                        ->arrayNode('languages')
                            ->info('Locale => provider language code, e.g. {pt: PT-BR} (DeepL defaults: en EN-GB, pt PT-PT).')
                            ->useAttributeAsKey('locale')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->arrayNode('glossary_domains')
                            ->info('Translation domains whose UI labels replace bold labels in the chapters (empty = no glossary).')
                            ->scalarPrototype()->end()
                            ->defaultValue(['messages'])
                        ->end()
                    ->end()
                ->end()
            ->end();

        return $tree;
    }

    private static function isLocale(mixed $locale): bool
    {
        return is_string($locale) && preg_match('/^[a-z]{2,3}(?:[_-][A-Za-z0-9]{2,8})*$/', $locale) === 1;
    }

    private static function isHttpUrl(mixed $url): bool
    {
        return is_string($url) && preg_match('#^https?://[^\s/]+#i', $url) === 1;
    }
}
